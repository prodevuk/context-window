#!/usr/bin/env node
// Drives the context-window MCP server (stdio) to create a context describing
// this repo and attach it to the current project. Demonstrates programmatic
// MCP usage end-to-end: spawn → initialize → tools/call create_context →
// tools/call attach_context.

import { spawn } from "node:child_process";
import { readFileSync, existsSync } from "node:fs";
import { resolve, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const mcpPath = join(root, "dist", "mcp", "server.js");
const manifestPath = join(root, ".context", "manifest.json");

if (!existsSync(mcpPath)) {
  console.error(`Missing ${mcpPath}. Run: npm run build`);
  process.exit(1);
}
if (!existsSync(manifestPath)) {
  console.error(
    `No manifest at ${manifestPath}. Run: node dist/cli/index.js project init`,
  );
  process.exit(1);
}

const { project_id } = JSON.parse(readFileSync(manifestPath, "utf8"));
if (!project_id) {
  console.error("Manifest has no project_id");
  process.exit(1);
}

const CONTEXT_NAME = "context-window — codebase overview";
const CONTEXT_DESCRIPTION =
  "Architecture, stack, key invariants, MCP tools, CLI commands, and test commands for the context-window codebase itself. Load when starting work in this repo.";
const CONTEXT_CONTENT = `# context-window — codebase overview

Local-mode context management system in TypeScript. Two first-class entities:
**Context** (standalone, reusable knowledge) and **Project** (ordered references
to contexts, emits a manifest.json). Local mode is feature-complete; cloud
mode is intentionally not implemented yet.

## Stack
- TypeScript, Node ≥ 20, ES2022 modules
- better-sqlite3 + FTS5 (storage + search)
- @modelcontextprotocol/sdk (stdio MCP server)
- commander (CLI)
- gpt-tokenizer (token counting)
- zod (schema validation)

## Source layout
- \`src/core/types.ts\` — every Zod schema and TS type for the data model
- \`src/core/context-service.ts\` — context CRUD + cross-project manifest propagation
- \`src/core/project-service.ts\` — attach/detach/reorder with list-insert semantics
- \`src/core/manifest-service.ts\` — manifest build, token budgeting, regen-all-referencing
- \`src/core/tokens.ts\` — gpt-tokenizer wrapper
- \`src/core/services.ts\` — DI container (\`buildServices()\`)
- \`src/core/errors.ts\` — DomainError + subclasses (NotFoundError, ConflictError, VersionConflictError, ValidationError)
- \`src/storage/repository.ts\` — storage contract (cloud mode would reimplement this)
- \`src/storage/sqlite/sqlite-repository.ts\` — better-sqlite3 implementation
- \`src/storage/sqlite/schema.ts\` — DDL + seeded categories
- \`src/mcp/server.ts\` — stdio entry point
- \`src/mcp/tools.ts\` — registry of 15 MCP tools (auto-listed)
- \`src/mcp/zod-to-json-schema.ts\` — minimal converter for tool listing
- \`src/cli/index.ts\` — commander root
- \`src/cli/context-commands.ts\`, \`src/cli/project-commands.ts\` — subcommands
- \`src/cli/active-project.ts\` — flag → env → manifest → cwd resolution
- \`src/config/paths.ts\` — DB and manifest path resolution

## Tests
- \`tests/services.test.mjs\` — 7 node:test unit tests over the service layer
- \`tests/smoke.mjs\` — 27 end-to-end checks spawning the built CLI + MCP

## Key invariants
- Manifest on disk is **derived state** — auto-regenerated by ContextService
  on create/update/archive/delete, and by ProjectService on attach/detach/reorder.
- \`status !== "active"\` contexts are excluded from manifests, budgets, and search.
- Positions in \`project_contexts\` are always normalised to \`0..n-1\` after any mutation.
- Token counts are computed on **write** and stored on the row, never on read.
- Storage layer must remain transport-agnostic (no \`process.cwd()\`, no \`fs\`).
- Core services must remain UI-agnostic (no \`console.log\`, no \`process.exit\`).
  Throw DomainError subclasses; transport layers format them.

## MCP server
- Stdio transport, built at \`dist/mcp/server.js\`.
- Project resolution order: \`--project-id\` flag → \`CONTEXT_PROJECT_ID\` env →
  \`project_id\` field of nearest \`.context/manifest.json\` walking up from cwd.
- Without an active project, tools like \`get_project_summary\`, \`attach_context\`,
  \`detach_context\` error with \`NO_ACTIVE_PROJECT\`. \`list_all_contexts\`,
  \`get_context\`, \`create_context\`, and \`search_contexts\` with \`scope: "all"\` still work.

### Tools (15)
- \`get_project_summary\` — call first; returns manifest metadata
- \`get_context\`, \`get_contexts_by_category\`, \`list_all_contexts\`
- \`search_contexts\` (\`scope: "project" | "all"\`) — FTS5, OR-of-prefix, active only
- \`get_context_budget\` — priority-ordered subset fitting a token budget
- \`create_context\`, \`update_context\` (optional \`expected_version\`)
- \`archive_context\`, \`delete_context\` (requires \`confirm: true\`)
- \`attach_context\` (upsert, list-insert positions), \`detach_context\`, \`reorder_contexts\`
- \`create_category\`, \`regenerate_manifest\`

## CLI
- \`context\`: \`init\`, \`new\`, \`list\`, \`search\`, \`show\`, \`edit\`, \`archive\`, \`delete\`, \`export\`, \`import\`, \`serve\`
- \`project\`: \`init\`, \`list\`, \`attach\`, \`detach\`, \`contexts\`, \`manifest\`, \`budget\`, \`reorder\`

## Build / test commands
- \`npm install && npm run build\` (writes \`dist/\`)
- \`npx tsc --noEmit\` (typecheck only)
- \`node --test tests/services.test.mjs\` (unit, requires built \`dist/\`)
- \`node tests/smoke.mjs\` (e2e, requires built \`dist/\`)

## Where to make common changes
- New MCP tool → append to \`src/mcp/tools.ts\` (auto-registered).
- New CLI command → \`src/cli/context-commands.ts\` or \`src/cli/project-commands.ts\`.
- New schema field → \`src/core/types.ts\` → \`src/storage/sqlite/schema.ts\` →
  row mapping in \`src/storage/sqlite/sqlite-repository.ts\`.
- Change manifest shape → \`src/core/manifest-service.ts#build\` + \`Manifest\` schema in \`types.ts\`.

## Cloud mode (not implemented)
Would add \`src/storage/postgres/\` and HTTP/SSE transport in \`src/mcp/\`. Core
services unchanged. Caching layer would key on \`context_id:version\`.
`;

async function main() {
  const mcp = startMcp(project_id);
  try {
    await mcp.request("initialize", {
      protocolVersion: "2024-11-05",
      capabilities: {},
      clientInfo: { name: "seed-self-context", version: "0.1.0" },
    });

    process.stdout.write(`create_context …\n`);
    const createResp = await mcp.request("tools/call", {
      name: "create_context",
      arguments: {
        name: CONTEXT_NAME,
        description: CONTEXT_DESCRIPTION,
        content: CONTEXT_CONTENT,
        category: "project",
        tags: ["typescript", "mcp", "context-management", "sqlite", "self"],
        priority: "important",
        created_by: "llm:claude-opus-4-7",
      },
    });
    assertOk(createResp, "create_context");
    const created = JSON.parse(createResp.result.content[0].text);
    const contextId = created.context.id;
    process.stdout.write(`  → id=${contextId}, tokens=${created.context.token_count}, warnings=${JSON.stringify(created.warnings)}\n`);

    process.stdout.write(`attach_context …\n`);
    const attachResp = await mcp.request("tools/call", {
      name: "attach_context",
      arguments: { context_id: contextId },
    });
    assertOk(attachResp, "attach_context");
    const attached = JSON.parse(attachResp.result.content[0].text);
    process.stdout.write(`  → project now has ${attached.context_refs.length} attached context(s)\n`);

    process.stdout.write(`get_project_summary …\n`);
    const summaryResp = await mcp.request("tools/call", {
      name: "get_project_summary",
      arguments: {},
    });
    assertOk(summaryResp, "get_project_summary");
    const summary = JSON.parse(summaryResp.result.content[0].text);
    process.stdout.write(
      `  → ${summary.contexts.length} context(s), ${summary.total_token_count} total tokens\n`,
    );
    for (const c of summary.contexts) {
      process.stdout.write(`    - ${c.name} [${c.priority}] (${c.token_count} tokens)\n`);
    }
  } finally {
    mcp.close();
  }
}

function startMcp(projectId) {
  const child = spawn("node", [mcpPath, "--project-id", projectId], {
    stdio: ["pipe", "pipe", "pipe"],
  });
  const pending = new Map();
  let buffer = "";
  let nextId = 1;

  child.stdout.on("data", (chunk) => {
    buffer += chunk.toString();
    let idx;
    while ((idx = buffer.indexOf("\n")) >= 0) {
      const line = buffer.slice(0, idx).trim();
      buffer = buffer.slice(idx + 1);
      if (!line) continue;
      try {
        const msg = JSON.parse(line);
        if (msg.id != null && pending.has(msg.id)) {
          pending.get(msg.id).resolve(msg);
          pending.delete(msg.id);
        }
      } catch {
        // ignore non-JSON
      }
    }
  });

  let stderr = "";
  child.stderr.on("data", (d) => (stderr += d.toString()));
  child.on("exit", (code) => {
    for (const { reject } of pending.values()) {
      reject(new Error(`MCP exited (${code}). stderr: ${stderr}`));
    }
    pending.clear();
  });

  return {
    request(method, params) {
      const id = nextId++;
      const promise = new Promise((resolveP, reject) => {
        pending.set(id, { resolve: resolveP, reject });
        setTimeout(() => {
          if (pending.has(id)) {
            pending.delete(id);
            reject(new Error(`Timeout waiting for ${method} id=${id}`));
          }
        }, 5000);
      });
      child.stdin.write(JSON.stringify({ jsonrpc: "2.0", id, method, params }) + "\n");
      return promise;
    },
    close() {
      try {
        child.stdin.end();
      } catch {
        // ignore
      }
      child.kill("SIGTERM");
    },
  };
}

function assertOk(resp, label) {
  if (resp.error) {
    throw new Error(`${label} JSON-RPC error: ${JSON.stringify(resp.error)}`);
  }
  if (resp.result?.isError) {
    throw new Error(`${label} tool error: ${resp.result.content?.[0]?.text ?? "unknown"}`);
  }
}

main().catch((err) => {
  console.error(err.message ?? err);
  process.exit(1);
});
